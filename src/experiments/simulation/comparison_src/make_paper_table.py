#!/usr/bin/env python3
"""Emits the safety-formulation comparison table as LaTeX."""
import os
import csv
import argparse

from comparison_config import display_name

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_CSV_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, "..", "results", "csv"))

ROWS = [
    ("Hard BF", None),
    ("Hard Dt-CBF", r"~\citep{zeng2021mpccbf}"),
    ("Slack BF", None),
    ("Slack Dt-CBF", None),
    ("LA Slack Dt-CBF", None),
    ("Slack Dt-HOCBF", None),
]
DEPLOYED = "LA Slack Dt-CBF"


def read_metrics(csv_path):
    db = {}
    with open(csv_path, newline="") as fh:
        for r in csv.DictReader(fh):
            db.setdefault(r["safety_level"], {})[int(r["n_robots"])] = r
    return db


def val(db, label, n, key, ci_keys):
    row = db.get(label, {}).get(n)
    if row is None:
        return None, None
    m = float(row[key])
    ci = 0.0
    for k in ci_keys:
        if row.get(k) not in (None, ""):
            ci = float(row[k])
            break
    return m, ci


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv-dir", default=DEFAULT_CSV_DIR)
    ap.add_argument("--case", default="phototaxis")
    ap.add_argument("--low", type=int, default=25)
    ap.add_argument("--high", type=int, default=100)
    a = ap.parse_args()

    path = os.path.join(a.csv_dir, f"{a.case}_metrics_vs_density.csv")
    if not os.path.isfile(path):
        raise SystemExit(f"metrics CSV not found: {path}\n"
                         f"(run the bench aggregate first)")
    db = read_metrics(path)

    cells = {}
    for label, _cite in ROWS:
        feas, feas_ci = val(db, label, a.low, "feasibility_rate_pct",
                            ("feasibility_ci95", "feasibility_rate_pct_ci95"))
        solve, solve_ci = val(db, label, a.low, "mean_solve_time_us",
                              ("mean_solve_time_us_ci95",))
        c_lo, c_lo_ci = val(db, label, a.low, "collisions_events_mean",
                            ("collisions_events_ci95",))
        c_hi, c_hi_ci = val(db, label, a.high, "collisions_events_mean",
                            ("collisions_events_ci95",))
        cells[label] = dict(feas=(feas, feas_ci),
                            solve=(None if solve is None else solve / 1000.0,
                                   None if solve_ci is None else solve_ci / 1000.0),
                            c_lo=(c_lo, c_lo_ci), c_hi=(c_hi, c_hi_ci))

    missing = [l for l, _ in ROWS if cells[l]["feas"][0] is None]
    if missing:
        print(f"% WARNING: no data for {missing} -- table is incomplete\n")

    PRECISION = {"feas": 2, "solve": 2, "c_lo": 0, "c_hi": 0}

    def best(field, higher_is_better):
        """Label of the UNIQUELY best row, else None.

        Bolding a tied value implies a distinction the data does not support: six
        formulations reach exactly 100.00% feasibility at the reference density, so
        emphasising one of them is arbitrary. Ties are compared on the value as
        PRINTED (not raw), because two rows that differ only below the displayed
        precision look identical to the reader.
        """
        vals = [(l, cells[l][field][0]) for l, _ in ROWS if cells[l][field][0] is not None]
        if not vals:
            return None
        prec = PRECISION[field]
        keyed = [(l, round(v, prec)) for l, v in vals]
        target = (max if higher_is_better else min)(keyed, key=lambda t: t[1])[1]
        winners = [l for l, v in keyed if v == target]
        return winners[0] if len(winners) == 1 else None

    best_of = {"feas": best("feas", True), "solve": best("solve", False),
               "c_lo": best("c_lo", False), "c_hi": best("c_hi", False)}

    def fmt(label, field, prec):
        m, ci = cells[label][field]
        if m is None:
            return "--"
        s = f"{m:.{prec}f} \\pm {ci:.{prec}f}"
        return f"$\\mathbf{{{s}}}$" if best_of[field] == label else f"${s}$"

    print("% ---- generated by make_paper_table.py; do not edit by hand ----")
    print(f"% source: {path}")
    print(f"% densities: N_b={a.low} (feasibility, solve time, collisions) and N_b={a.high} (collisions)")
    for label, cite in ROWS:
        name = display_name(label)
        shown = f"\\textbf{{{name}}}" if label == DEPLOYED else name
        if cite:
            shown += cite
        print(f"    {shown:<38} & {fmt(label,'feas',2)} & {fmt(label,'solve',2)} "
              f"& {fmt(label,'c_lo',0)} & {fmt(label,'c_hi',0)} \\\\")
    print("% ---- end generated rows ----\n")

    print("% Cross-check values for the section 5 prose:")
    for label, _ in ROWS:
        c = cells[label]
        if c["feas"][0] is None:
            continue
        print(f"%   {display_name(label):<24} feas={c['feas'][0]:.2f}%  "
              f"solve={c['solve'][0]:.2f}ms  coll@{a.low}={c['c_lo'][0]:.0f}  "
              f"coll@{a.high}={c['c_hi'][0]:.0f}")
    hard = [l for l in ("Hard BF", "Hard Dt-CBF") if cells[l]["feas"][0] is not None]
    if hard:
        lo = min(cells[l]["feas"][0] for l in hard)
        hi = max(cells[l]["feas"][0] for l in hard)
        print(f"%   hard-formulation feasibility band at N_b={a.low}: {lo:.2f}%--{hi:.2f}%")
    slack = [l for l, _ in ROWS if l not in ("Hard BF", "Hard Dt-CBF")
             and cells[l]["feas"][0] is not None]
    if slack:
        print(f"%   lowest slacked feasibility: {min(cells[l]['feas'][0] for l in slack):.2f}%")
    if best_of["c_hi"]:
        print(f"%   fewest contacts at N_b={a.high}: {display_name(best_of['c_hi'])}")
        worst = max(((l, cells[l]["c_hi"][0]) for l, _ in ROWS
                     if cells[l]["c_hi"][0] is not None), key=lambda t: t[1])
        print(f"%   most contacts at N_b={a.high}: {display_name(worst[0])} ({worst[1]:.0f})")


if __name__ == "__main__":
    main()
